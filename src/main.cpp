#include "db/Database.hpp"
#include "db/Migration.hpp"
#include "ui/App.hpp"

#include <clocale>

// Точка входа в приложение.
// Открывает базу данных, применяет миграции (создаёт таблицы при первом
// запуске), создаёт объект App и запускает главный цикл FLTK.
// Вся дальнейшая логика — в App::run(): seed администратора,
// создание окон входа и главного, обработка событий.
int main() {
    // Устанавливаем локаль из окружения — необходимо для корректного
    // отображения кириллицы во FLTK (UTF-8).
    setlocale(LC_ALL, "");

    // Открываем файл БД. Если его нет — SQLite создаст автоматически.
    // Путь относительный: файл music.db создаётся в текущей рабочей
    // директории (там, откуда запущена программа).
    Database db("music.db");

    // Применяем миграции: создаём таблицы, если их нет,
    // и вставляем базовые роли (admin, manager).
    // Идемпотентно
    runMigration(db);

    // App владеет сервисами и окнами, управляет состоянием сессии.
    // Конструктор только сохраняет ссылку на БД и создаёт сервисы,
    // окна создаются позже, в run().
    App app(db);

    // Запуск event loop: блокирует поток до завершения приложения.
    app.run();

    return 0;
}
